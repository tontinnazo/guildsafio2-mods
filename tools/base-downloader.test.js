'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs/promises');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const { getBaseArchive } = require('../app/base-downloader');
test('base archive is downloaded, verified, cached and repaired after corruption', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'guildsafio-base-test-'));
  const originalFetch = global.fetch;
  t.after(async () => { global.fetch = originalFetch; await fs.rm(root, { recursive: true, force: true }); });
  const bytes = Buffer.from('base archive fixture');
  const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
  await fs.writeFile(path.join(root, 'base-config.json'), JSON.stringify({ url: 'https://github.com/tontinnazo/guildsafio2-mods/releases/download/base-v11/game-base-v11.7z', sha256, size: bytes.length }));
  let calls = 0; let corrupt = false;
  global.fetch = async () => { calls++; return new Response(corrupt ? Buffer.alloc(bytes.length) : bytes); };
  const messages = [];
  const archive = await getBaseArchive(root, root, p => messages.push(p));
  assert.deepEqual(await fs.readFile(archive), bytes);
  await getBaseArchive(root, root, () => {});
  assert.equal(calls, 1);
  assert.equal(messages.at(-1).percent, 100);
  await fs.writeFile(archive, 'damaged');
  corrupt = true;
  await assert.rejects(getBaseArchive(root, root, () => {}), /dañados/);
  corrupt = false;
  await getBaseArchive(root, root, () => {});
  assert.deepEqual(await fs.readFile(archive), bytes);
  assert.equal(calls, 3);
});
